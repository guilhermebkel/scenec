const MAX_ENUM_SHOWN = 12;

function typeOf(node) {
  if (node.enum) {
    const shown = node.enum.slice(0, MAX_ENUM_SHOWN).join(" | ");
    return node.enum.length > MAX_ENUM_SHOWN ? `${shown} | ...` : shown;
  }
  if (node.const !== undefined) {
    return String(node.const);
  }
  const variants = node.anyOf ?? node.oneOf;
  if (variants) {
    const types = [...new Set(variants.map((variant) => typeOf(variant)))];
    return types.join(" or ");
  }
  if (node.type === "array") {
    return node.prefixItems ? `[${node.prefixItems.map((item) => typeOf(item)).join(", ")}]` : `${typeOf(node.items ?? {})}[]`;
  }
  return String(node.type ?? "any");
}

function tableOf(properties) {
  const rows = Object.entries(properties).map(([name, node]) => {
    const description = (node.description ?? "").replaceAll("|", "\\|").replaceAll("\n", " ");
    return `| \`${name}\` | ${typeOf(node).replaceAll("|", "\\|")} | ${description} |`;
  });
  return ["| Field | Type | Meaning |", "| --- | --- | --- |", ...rows].join("\n");
}

function sectionOf(title, node) {
  const properties = node?.properties ?? node?.additionalProperties?.properties ?? node?.items?.properties;
  return properties ? `## ${title}\n\n${tableOf(properties)}\n` : "";
}

export function buildDsl(schema, layout) {
  const props = schema.properties;
  const topEntries = Object.entries(props).map(([name, node]) => [name, { ...node, description: node.description ?? "" }]);
  const top = tableOf(Object.fromEntries(topEntries));
  const vocabulary = Object.entries(layout).map(([name, values]) => `- \`${name}\`: ${values.join(", ")}`).join("\n");
  return [
    "# Scene language (generated, do not edit)",
    "",
    "Generated by `pnpm skill:refs` from the Zod schema. Unknown fields are not errors: the compiler warns and suggests the closest name.",
    "",
    "## Top level",
    "",
    top,
    "",
    sectionOf("canvas", props.canvas),
    sectionOf("objects (each entry under `objects:`)", props.objects),
    sectionOf("text (each item)", props.text),
    "## Vocabulary",
    "",
    vocabulary,
    "",
  ].join("\n");
}

export function buildCatalog({ assets, groups, kits, themes, poses }) {
  const assetRows = assets.map((asset) => `| \`${asset.id}\` | ${asset.kind} | ${asset.width}x${asset.height} | ${asset.synonyms.join(", ")} |`);
  const groupRows = groups.map((group) => `| \`${group.id}\` | ${group.description} | ${Object.values(group.parts).join(", ")} |`);
  const kitRows = kits.map((kit) => `- \`${kit.id}\`: ${kit.description}`);
  const poseLines = Object.entries(poses).map(([name, values]) => `- \`${name}\`: ${values.join(", ")}`);
  return [
    "# Catalog (generated, do not edit)",
    "",
    "Generated by `pnpm skill:refs`. Query live with `npx @guilhermebkel/scenec@1 catalog <assets|groups|kits|themes|poses|layout>`.",
    "",
    `## Assets (${assets.length})`,
    "",
    "| Id | Kind | Size | Synonyms |",
    "| --- | --- | --- | --- |",
    ...assetRows,
    "",
    `## Groups (${groups.length})`,
    "",
    "| Id | What it is | Parts |",
    "| --- | --- | --- |",
    ...groupRows,
    "",
    "## Kits",
    "",
    ...kitRows,
    "",
    "## Themes",
    "",
    themes.map((theme) => `\`${theme}\``).join(", "),
    "",
    "## Poses and expressions",
    "",
    ...poseLines,
    "",
  ].join("\n");
}
