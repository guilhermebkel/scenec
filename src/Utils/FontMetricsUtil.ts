  private static readonly FONT_TO_KEY: Record<FontName, Record<"regular" | "bold", FontTableKey>> = {
    sans: { regular: "sans", bold: "sansBold" },
    serif: { regular: "serif", bold: "serif" },
    hand: { regular: "hand", bold: "hand" },
  };

  static lineEm(line: string, fontName: FontName, isBold: boolean): number {
    // Why: advance widths in em are read from the bundled font files, so a highlight box fits the real glyphs; kerning is not applied.
    const key = FontMetricsUtil.FONT_TO_KEY[fontName][isBold ? "bold" : "regular"];
    const table = FontMetricsUtil.KEY_TO_TABLE[key];
    let total = 0;
    for (const char of line) {
      total += table[char.codePointAt(0) ?? 0] ?? FontMetricsUtil.UNKNOWN_EM;
    }
    return total;
  }
